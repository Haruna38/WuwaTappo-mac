#!/usr/bin/env python3
"""Keep the Tauri ACL in sync with the command table.

The frontend is served from http://localhost:1421, a "remote" origin for
Tauri's ACL, so every app command needs an explicit permission. This reads the
`generate_handler!` list in src-tauri/src/lib.rs and rewrites the command list
in build.rs and the `allow-*` entries in capabilities/default.json.
Run it after adding or removing a command.
"""
import json
import pathlib
import re

TAURI = pathlib.Path(__file__).resolve().parent.parent / "src-tauri"

lib = (TAURI / "src" / "lib.rs").read_text()
start = lib.index("generate_handler![")
block = lib[start : lib.index("])", start)]
commands = re.findall(r"::([a-z_0-9]+),", block)

(TAURI / "build.rs").write_text(
    """fn main() {
    // App commands need explicit permissions because the frontend is served
    // from http://localhost:1421 (a "remote" origin for Tauri's ACL); see
    // src/server.rs for why. Generated by scripts/sync-permissions.py.
    tauri_build::try_build(
        tauri_build::Attributes::new().app_manifest(tauri_build::AppManifest::new().commands(&[
%s
        ])),
    )
    .expect("failed to run tauri-build");
}
"""
    % "\n".join(f'            "{c}",' for c in commands)
)

cap_path = TAURI / "capabilities" / "default.json"
cap = json.loads(cap_path.read_text())
wanted = ["allow-" + c.replace("_", "-") for c in commands]
plugin = [p for p in cap["permissions"] if ":" in p]
cap["permissions"] = plugin + wanted
cap_path.write_text(json.dumps(cap, indent=2) + "\n")
print(f"{len(commands)} commands")
